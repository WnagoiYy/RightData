import { spawnSync } from 'node:child_process';
import { mkdirSync, copyFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
const root = resolve('.');
const built = spawnSync('cargo', ['build', '--locked', '--manifest-path', 'client/network-service/Cargo.toml', '--target-dir', 'client/network-service/target'], { stdio: 'inherit', windowsHide: true });
if (built.status !== 0) throw new Error('Service build failed');
const windows = process.platform === 'win32';
const source = resolve(root, `client/network-service/target/debug/rightdata-network-service${windows ? '.exe' : ''}`);
const destination = resolve(root, windows ? 'client/target/x86_64-pc-windows-msvc/release/rightdata-network-service.exe' : 'client/target/macos-resources/rightdata-network-service');
mkdirSync(dirname(destination), { recursive: true });
copyFileSync(source, destination);
